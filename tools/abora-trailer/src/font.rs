/// Renders `text` as rows of characters (one space between glyphs).
pub fn render(text: &str) -> Vec<Vec<char>> {
    let mut rows = vec![Vec::new(); ROWS];
    for (i, c) in text.chars().enumerate() {
        for (r, line) in glyph(c).iter().enumerate() {
            if i > 0 {
                rows[r].push(' ');
            }
            rows[r].extend(line.chars());
        }
    }
    rows
}

pub fn width(text: &str) -> usize {
    render(text).first().map_or(0, Vec::len)
}

/// Solid faces are drawn bright, the box-drawing shadow darker.
pub fn is_face(c: char) -> bool {
    c == '█'
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_glyph_is_rectangular() {
        for c in "ABCEILNORSTVX0123456789. ".chars() {
            let rows = glyph(c);
            let w = rows[0].chars().count();
            for row in rows {
                assert_eq!(row.chars().count(), w, "glyph {c:?} has ragged rows");
            }
        }
    }

    #[test]
    fn the_logo_fits_an_80_column_terminal() {
        assert_eq!(width("ABORA OS"), 68);
        assert!(render("ABORA OS").iter().all(|r| r.len() == 68));
    }
}
